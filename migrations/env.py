"""Alembic environment.

Three things this file does that the stock template does not, each for a specific reason:

1. READS THE URL FROM `Settings`, NOT FROM alembic.ini.
   One source of truth for configuration (core/config.py). A connection string in a committed
   file is how production credentials end up in git — which is, literally, a thing our product
   exists to detect in other people's infrastructure. We do not get to do it in our own.

2. RUNS ASYNC (asyncpg).
   Our engine is async, so the same DSN works for both the app and migrations. Without this,
   `postgresql+asyncpg://...` fails inside Alembic and you end up maintaining a SECOND,
   sync DSN — which drifts from the first.

3. `compare_type=True` and `compare_server_default=True`.
   Off by default. With them off, changing a column from VARCHAR(50) to VARCHAR(100), or
   altering a default, produces an EMPTY autogenerated migration. Silent no-ops are the worst
   possible failure mode for a migration tool: you deploy, nothing changes, and you have no
   idea why.

⚠️ WHAT AUTOGENERATE STILL CANNOT SEE (docs/04) — you must hand-write these:
       - Row-Level Security policies (`CREATE POLICY`, `FORCE ROW LEVEL SECURITY`)
       - partial indexes with a WHERE clause
       - new values added to an existing enum
       - anything expressed as raw DDL
   Which is precisely why the rule is "autogenerate, then READ AND EDIT the result". RLS is
   layer 3 of our four-layer tenant isolation model; it will never appear by magic.
"""

from __future__ import annotations

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

# IMPORTANT: importing `models` registers every ORM class on `Base.metadata`.
# A model that is never imported is INVISIBLE to autogenerate, which then emits an empty
# migration and you deploy a missing table. See db/models/__init__.py — the explicit import
# list there is the cure, and this line is what activates it.
import cloudguard_core.db.models  # noqa: F401
from cloudguard_core.config import get_settings
from cloudguard_core.db.base import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Inject the DSN from the environment (reason #1 above).
config.set_main_option("sqlalchemy.url", str(get_settings().database_url))

# What the schema SHOULD look like. Alembic diffs the live database against this.
target_metadata = Base.metadata


def _configure(connection: Connection) -> None:
    """Shared migration context options."""
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,  # reason #3
        compare_server_default=True,  # reason #3
        # Emit transactional DDL. Postgres supports it — so a migration that fails halfway
        # ROLLS BACK ENTIRELY rather than leaving the schema in an undefined half-applied
        # state that no `downgrade()` can describe. (MySQL cannot do this. It is one of the
        # quieter reasons to run Postgres.)
        transaction_per_migration=True,
    )


def run_migrations_offline() -> None:
    """Generate SQL without connecting to a database (`alembic upgrade head --sql`).

    Used when a DBA or a change-management process must review the exact DDL before it runs
    against production. We do not need this yet — but it costs nothing to keep working, and
    the first enterprise customer who asks for it will ask with a deadline attached.
    """
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    _configure(connection)
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    """Connect and apply migrations. The normal path."""
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        # NullPool: a migration process runs once and exits. A connection pool would be
        # pointless overhead and can leave connections lingering after the script finishes.
        poolclass=pool.NullPool,
    )

    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)

    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
